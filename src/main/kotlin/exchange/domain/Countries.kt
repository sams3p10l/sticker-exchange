package exchange.domain

import java.text.Collator
import java.util.Locale

data class Country(val code: String, val name: String)

const val DEFAULT_COUNTRY_CODE = "RS"

private val serbian = Collator.getInstance(Locale.forLanguageTag("sr-Latn")).apply {
    strength = Collator.PRIMARY
}

val countries: List<Country> = countryNames()
    .map { (code, name) -> Country(code, name) }
    .sortedWith { left, right -> serbian.compare(left.name, right.name) }

private val countriesByCode = countries.associateBy { it.code }

fun isCountry(code: String): Boolean = code in countriesByCode

fun countryName(code: String): String? = countriesByCode[code]?.name

